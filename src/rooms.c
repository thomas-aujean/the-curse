// Room templates, drawn in 16 x 16 blocks (2 x 2 tiles): one screen = 20 x 14 blocks.
//   #  wall          -  one-way platform (top tile row)          .  empty
//   w f B    spawn points (feet on the bottom of the block): walker, flyer, boss,
//   a n g j  archer, ninja, shield guard, jelly        o  breakable prop (coins)   c  chest
//   L R U D  door blocks: open when the floor map has a neighbour on that side, wall otherwise.
//            An open D (hole in the floor) is covered by a platform: DOWN + C drops into the room
//            below, and coming up from below the player lands on it.
// The hero's box is 40 px tall: doors are 3 blocks high and nothing hangs lower than 48 px over a floor.
// The top row is ceiling (a closed U door is wall too): the highest platform sits on row 4, never higher.
// Climbing rule: platforms at most 3 blocks (48 px) apart vertically and 3 blocks apart sideways; a full
// jump is 96 px. tests/level_test.c walks every template with that rule: each door must lead to the others.
// A room holds at most MAX_ENEMIES spawn points and MAX_PROPS props and chests (the rest is ignored).

