ART = {
    "jar": JAR, "urn": URN, "crate": CRATE, "candle": CANDLE,
    "bronze": chest("6", "5", False), "bronze_open": chest("6", "5", True),
    "silver": chest("9", "a", False), "silver_open": chest("9", "a", True),
    "gold": chest("5", "b", False), "gold_open": chest("5", "b", True),
}


def pixel(ch):
    if ch == ".":
        return 0
    if ch.isdigit():
        return int(ch)
    return 10 + "abcde".index(ch)


def sheet():
    img = [[0] * (16 * len(ORDER)) for _ in range(16)]
    for i, name in enumerate(ORDER):
        art = ART[name]
        for y in range(16):
            row = art[y].ljust(16, ".")[:16]
            for x in range(16):
                img[y][i * 16 + x] = pixel(row[x])
    return img
