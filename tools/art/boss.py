"""The cursed captain, the floor's boss (Thomas, 2026-11-18: "go for the bosses"): PixelLab character
2ce2a203 (88 x 88, side view) and its states windup 9044b47e, strike 325e9a81 (112 x 112 canvases, same
scale) and walk 5e1bedf2, in art_in/boss/captain/, facing right.

About 87 px tall, twice the hero. Too big for the enemies' 4-part frames: each pose is cut into a grid
of hardware sprites up to 4 x 4 tiles, every sprite shrunk to the tiles that hold pixels. All poses fit
in the enemies' stretch of video memory (GFX_ENEMIES, ENEMY_TILE_COUNT tiles): the boss room has no other
enemy, so its tiles are loaded there when the player walks in (gfx_loadCaptain) and the enemies'
come back on the way out. Colours: PAL2 slots 1..13 (the enemies' palette, so the floor's tint and the
Void's PAL3 work on it too).
"""
import os

from knight import dist
from pngread import read_png

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
SRC = os.path.join(ROOT, "art_in", "boss", "captain")

# Engine pose -> picture. Order = BF_* in inc/boss_frames.h.
POSES = [("walk_a", "east"), ("walk_b", "walk"), ("windup", "windup"), ("strike", "strike")]
MAX_TILES = 462   # ENEMY_TILE_COUNT: the enemies' place


def _load(name):
    px, _ = read_png(os.path.join(SRC, name + ".png"))
    return {(x, y): p[:3] for y, row in enumerate(px) for x, p in enumerate(row) if p[3] > 127}


def _anchor(px):
    """(centre x, ground y): the feet on the ground, the body centred on its armoured legs (the bottom
    rows without the blade, which is thin and pale)."""
    ground = max(y for _, y in px)
    feet = [x for (x, y), c in px.items() if y >= ground - 10 and sum(c) < 300]
    feet.sort()
    return feet[len(feet) // 2], ground


def _sprites(px, cx, ground):
    """[(dx, dy, w, h, pixels)]: sprites (tiles) covering the pose, dx / dy from the centre and from
    just below the feet."""
    xs, ys = [x for x, _ in px], [y for _, y in px]
    x0, y0 = min(xs), min(ys)
    w, h = (max(xs) - x0) // 8 + 1, (max(ys) - y0) // 8 + 1   # tiles
    out = []
    for gy in range(0, h, 4):
        for gx in range(0, w, 4):
            cols = [c for c in range(gx, min(gx + 4, w))
                    if any((x0 + c * 8 + x, y0 + r * 8 + y) in px
                           for r in range(gy, min(gy + 4, h)) for x in range(8) for y in range(8))]
            rows = [r for r in range(gy, min(gy + 4, h))
                    if any((x0 + c * 8 + x, y0 + r * 8 + y) in px
                           for c in range(gx, min(gx + 4, w)) for x in range(8) for y in range(8))]
            if not cols:
                continue
            c0, c1, r0, r1 = min(cols), max(cols), min(rows), max(rows)
            out.append((x0 + c0 * 8 - cx, y0 + r0 * 8 - ground - 1, c1 - c0 + 1, r1 - r0 + 1,
                        x0 + c0 * 8, y0 + r0 * 8))
    return out


def build(pal):
    """(tile sheet 128 px wide, C header) on PAL2 `pal`."""
    cache = {}

    def index(c):
        if c not in cache:
            cache[c] = min(range(1, 14), key=lambda i: dist(pal[i], c))
        return cache[c]

    tiles, frames, sprites = [], [], []
    for name, picture in POSES:
        px = _load(picture)
        cx, ground = _anchor(px)
        parts = _sprites(px, cx, ground)
        frames.append("    { %d, %d },   /* %s */" % (len(sprites), len(parts), name))
        for dx, dy, w, h, sx, sy in parts:
            sprites.append("    { %d, %d, %d, %d, %d }," % (dx, dy, w, h, len(tiles)))
            for tx in range(w):   # column by column, as the VDP reads a sprite
                for ty in range(h):
                    tiles.append([[index(px[(sx + tx * 8 + x, sy + ty * 8 + y)])
                                   if (sx + tx * 8 + x, sy + ty * 8 + y) in px else 0
                                   for x in range(8)] for y in range(8)])
    assert len(tiles) <= MAX_TILES, "the boss needs %d tiles, the enemies' place has %d" % (len(tiles), MAX_TILES)
    count = len(tiles)
    while len(tiles) % 16:
        tiles.append([[0] * 8 for _ in range(8)])
    sheet = [[c for t in tiles[r:r + 16] for c in t[y]] for r in range(0, len(tiles), 16) for y in range(8)]
    header = ("// Generated by tools/art/make_art.py from tools/art/boss.py: do not edit.\n"
              "#ifndef BOSS_FRAMES_H\n#define BOSS_FRAMES_H\n\n"
              "enum { " + ", ".join("BF_" + n.upper() for n, _ in POSES) + ", BF_COUNT };\n\n"
              "#define BOSS_TILE_COUNT %d\n#define BOSS_SPRITE_COUNT %d\n\n" % (count, len(sprites))
              + "// Per pose: first sprite, number of sprites.\n"
              "#define BOSS_FRAME_TABLE \\\n{ \\\n" + "".join(f + " \\\n" for f in frames) + "}\n\n"
              "// Per sprite: x from the boss's centre (facing right), y from just below its feet, width and\n"
              "// height in tiles, first tile (from GFX_ENEMIES).\n"
              "#define BOSS_SPRITE_TABLE \\\n{ \\\n" + "".join(s + " \\\n" for s in sprites) + "}\n\n#endif\n")
    return sheet, header


def preview(pal):
    """The poses put back together from their sprites, as the engine draws them: 128 x 112 cells."""
    sheet, header = build(pal)
    table = [list(map(int, l.split("{")[1].split("}")[0].split(","))) for l in header.splitlines()
             if l.startswith("    { ") and "/*" not in l]
    frames = [list(map(int, l.split("{")[1].split("}")[0].split(","))) for l in header.splitlines()
              if l.startswith("    { ") and "/*" in l]
    out = [[0] * (128 * len(frames)) for _ in range(112)]
    for f, (first, n) in enumerate(frames):
        for dx, dy, w, h, t in table[first:first + n]:
            for tx in range(w):
                for ty in range(h):
                    for y in range(8):
                        for x in range(8):
                            c = sheet[(t // 16) * 8 + y][(t % 16) * 8 + x]
                            X, Y = f * 128 + 64 + dx + tx * 8 + x, 108 + dy + ty * 8 + y
                            if c and 0 <= Y < 112:
                                out[Y][X] = c
                    t += 1
    return out
