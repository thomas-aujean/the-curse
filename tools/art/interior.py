"""World 2, inside the castle (Thomas, 2026-11-19: "world 1 and 2"): cold grey-violet stone, oak beams
for platforms, a hall of gothic windows on the sunset behind, banners, torches, candelabras and empty
suits of armour. All PixelLab (docs/pixellab.md), in art_in/castle/ and art_in/tiles/.

Same contracts as world 1, so the engine only swaps the pictures (gfx_setWorld):
  res/castle2.png   room tiles in the castle.py order (stone, cracked, the beam's 3 x 5 pieces, deep)
                    and PAL0 for the world: 1..9 the room, 10..14 the far wall, 15 the text
  res/far2_tiles.png, inc/far2_map.h   the far wall on plane B (64 x 32), its runs in video memory
  res/decor2.png, inc/decor2_tiles.h   the decor (DECOR2_*)
"""
import os

from knight import dist, median_cut
from pngread import read_png
import outdoor

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
ART = os.path.join(ROOT, "art_in")
TILESET = "castle_interior_tileset"   # PixelLab sidescroller tileset 086aebc0
BEAM = "castle/beam.png"              # PixelLab pixflux feacd76f
BEAM_COLUMNS = [16, 24, 53, 61, 64]   # middle A, middle B, end, tip 1 (the bracket), tip 2 (nothing)
WALL = "castle/back_wall.png"         # PixelLab pixflux d15b8f62: two bays of a gothic hall, 256 x 224
BAY = 128                              # one bay (pillar, window), repeated: half the tiles
# Ground decor first, then the kinds hung on the wall (no foot); the engine's DECOR2_* order.
DECOR = [
    ("CANDELABRA", "castle/candelabra.png"),
    ("ARMOR", "castle/armor.png"),
    ("BANNER", "castle/banner.png"),
    ("TORCH", "castle/torch.png"),
]
WALL_KINDS = ("BANNER", "TORCH")
TILE_USER_INDEX = 16
RANGES = [(228, 252), (576, 24), (656, 44), (1960, 56)]   # the far background's places (far.py)


def _load(rel):
    rows, (w, h) = read_png(os.path.join(ART, rel))
    return {(x, y): rows[y][x][:3] for y in range(h) for x in range(w) if rows[y][x][3] >= 128}


def palette():
    """PAL0 slots 1..9: 5 for the stone of the tileset, 4 for the beam and the decor among the colours
    the stone does not give (each picture weighed the same, so a small torch still gets its flame)."""
    stone = {}
    for c in _load(os.path.join("tiles", TILESET + ".png")).values():
        stone[c] = stone.get(c, 0) + 1
    base = median_cut(stone, 5)
    counts = {}
    for px in [_load(BEAM)] + [_load(f) for _, f in DECOR]:
        n = len(px)
        for c in px.values():
            if min(dist(c, g) for g in base) > 1200:
                counts[c] = counts.get(c, 0) + 10000.0 / n
    return sorted(base + median_cut(counts, 4), key=sum)


def beam_tiles(pal):
    return outdoor.branch_tiles(pal, BEAM, BEAM_COLUMNS)


def far(pal0):
    """pal0: PAL0 with the room's slots 1..9 set. Picks slots 10..14 for the wall (its colours the room's
    do not give: the sunset in the windows), then cuts one bay repeated over the 512 x 256 plane, the
    wall's top 32 rows above it. Returns (pal0 with 10..14, tile sheet rows, tile count, far2_map.h,
    the plane's picture for previews)."""
    rows, (w, h) = read_png(os.path.join(ART, WALL))
    # The bay starting where the picture repeats best (seam between two columns 128 px apart).
    x0 = min(range(BAY), key=lambda x: sum(dist(rows[y][x][:3], rows[y][(x + BAY) % w][:3]) for y in range(h)))
    counts = {}
    for y in range(h):
        for x in range(x0, x0 + BAY):
            c = rows[y][x][:3]
            if min(dist(c, g) for g in pal0[1:10]) > 900:
                counts[c] = counts.get(c, 0) + 1
    pal = pal0[:10] + sorted(median_cut(counts, 5), key=sum) + pal0[15:16]
    cache = {}

    def index(c):
        if c not in cache:
            cache[c] = 1 + min(range(14), key=lambda i: dist(pal[1 + i], c))
        return cache[c]

    W, H = 512, 256
    img = [[index(rows[max(0, y - (H - h)) if y >= H - h else y][x0 + x % BAY][:3]) for x in range(W)]
           for y in range(H)]
    total = sum(n for _, n in RANGES)
    for slack in range(0, 512, 8):
        tiles, plane = _cut(img, pal, slack)
        if len(tiles) <= total:
            break
    assert len(tiles) <= total, "castle far wall: %d tiles for %d places" % (len(tiles), total)
    vram, runs, k = [], [], 0
    for start, n in RANGES:
        take = min(n, len(tiles) - k)
        if take <= 0:
            break
        runs.append((k, TILE_USER_INDEX + start, take))
        vram += [TILE_USER_INDEX + start + i for i in range(take)]
        k += take
    count = len(tiles)
    while len(tiles) % 16:
        tiles.append(tuple(tuple([0] * 8) for _ in range(8)))
    sheet = [[0] * 128 for _ in range(len(tiles) // 16 * 8)]
    for i, t in enumerate(tiles):
        for y in range(8):
            sheet[(i // 16) * 8 + y][(i % 16) * 8:(i % 16) * 8 + 8] = list(t[y])
    m = ["// Generated by tools/art/interior.py: world 2's far wall on plane B (64 x 32, PAL0, low priority)",
         "// and the runs of res/far2_tiles.png in video memory: { first tile, video memory index, count }.",
         "#ifndef FAR2_MAP_H", "#define FAR2_MAP_H", "",
         "#define FAR2_RUNS %d" % len(runs),
         "static const u16 FAR2_RUN[FAR2_RUNS][3] = { %s };" % ", ".join("{ %d, %d, %d }" % r for r in runs),
         "static const u16 FAR2_MAP[64 * 32] =", "{"]
    for ty in range(H // 8):
        m.append("    " + ", ".join("0x%04X" % ((vf << 12) | (hf << 11) | vram[i])
                                    for i, hf, vf in plane[ty * 64:(ty + 1) * 64]) + ",")
    m += ["};", "", "#endif", ""]
    return pal, sheet, count, "\n".join(m), img


def _cut(img, pal, slack):
    """Tiles with mirrors shared; a tile within `slack` (summed colour distance / 1024) of one kept
    takes its place, so the wall fits its video memory."""
    tiles, known, plane = [], {}, []

    def far_from(a, b):
        d = 0
        for ra, rb in zip(a, b):
            for x, y in zip(ra, rb):
                if x != y:
                    d += dist(pal[x], pal[y]) >> 10
                    if d > slack:
                        return True
        return False
    for ty in range(len(img) // 8):
        for tx in range(len(img[0]) // 8):
            t = tuple(tuple(img[ty * 8 + y][tx * 8:tx * 8 + 8]) for y in range(8))
            entry = None
            for hf in (0, 1):
                for vf in (0, 1):
                    v = tuple(r[::-1] for r in t) if hf else t
                    v = v[::-1] if vf else v
                    if v in known:
                        entry = (known[v], hf, vf)
                        break
                if entry:
                    break
            if not entry and slack:
                for i, k in enumerate(tiles):
                    if not far_from(t, k):
                        entry = (i, 0, 0)
                        break
            if not entry:
                known[t] = len(tiles)
                tiles.append(t)
                entry = (known[t], 0, 0)
            plane.append(entry)
    return tiles, plane


def decor(pal, ground):
    grass = set(outdoor.GRASS)
    outdoor.GRASS.clear()   # no grass blades in front of the feet indoors
    out = outdoor.decor(pal, ground, DECOR, "DECOR2", WALL_KINDS)
    outdoor.GRASS.update(grass)
    return out
